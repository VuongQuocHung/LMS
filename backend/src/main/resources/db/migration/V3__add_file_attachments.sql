CREATE TABLE essay_drafts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id),
    content TEXT NOT NULL DEFAULT '',
    CONSTRAINT uq_draft_student UNIQUE (assignment_id, student_id)
);

CREATE TABLE file_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_name VARCHAR(255) NOT NULL,
    storage_key VARCHAR(50) NOT NULL UNIQUE,
    content_type VARCHAR(150) NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes > 0),
    uploaded_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lesson_id BIGINT REFERENCES lessons(id) ON DELETE CASCADE,
    assignment_id BIGINT REFERENCES assignments(id) ON DELETE CASCADE,
    draft_id BIGINT REFERENCES essay_drafts(id) ON DELETE CASCADE,
    submission_id BIGINT REFERENCES assignment_submissions(id) ON DELETE CASCADE,
    CONSTRAINT ck_attachment_owner CHECK (
        (CASE WHEN lesson_id IS NULL THEN 0 ELSE 1 END) +
        (CASE WHEN assignment_id IS NULL THEN 0 ELSE 1 END) +
        (CASE WHEN draft_id IS NULL THEN 0 ELSE 1 END) +
        (CASE WHEN submission_id IS NULL THEN 0 ELSE 1 END) = 1
    )
);
CREATE INDEX ix_files_lesson ON file_attachments(lesson_id);
CREATE INDEX ix_files_assignment ON file_attachments(assignment_id);
CREATE INDEX ix_files_draft ON file_attachments(draft_id);
CREATE INDEX ix_files_submission ON file_attachments(submission_id);
